@eqx.filter_value_and_grad
def loss_and_grads_pretrain(
        diff_model: PyTree,
        static_model: PyTree,
        conf: Dict,
        input_data: Float[Array, '...'],
        targets: Float[Array, '...'],
):
    # recombine the two parts of the model
    model = eqx.combine(diff_model, static_model)
    # Get model output (inflated cell-line-specific parameter deviations)
    pred = jax.vmap(model)(input_data)["inflated"]
    # Loss comprises MSE between predicted kinetic parameter deviations and
    #  those obtained from ODE pretraining.
    loss_value = (
            mse(pred.flatten(), targets.flatten())
            + model.l1_encode_reg(scale=conf["l1reg_encode"])
            + model.orth_encode_reg(scale=conf["oreg_encode"])
            + model.l1_inflate_reg(scale=conf["l1reg_inflate"])
            + model.orth_inflate_reg(scale=conf["oreg_inflate"])
    )

    # if two-headed autoencoder, add decoder terms (reconstruction, encoder-decoder symmetry, and regularisation terms
    # with same scales as encoder)
    if model.reconstruct:
        loss_value += (
                model.l1_decode_reg(scale=conf["l1reg_encode"])
                + model.orth_decode_reg(scale=conf["oreg_encode"])
                + model.reconstruction_loss(x=input_data, scale=conf["recon_loss"])
                + model.symmetry_loss(scale=conf["symm_reg"])
        )
    return loss_value


