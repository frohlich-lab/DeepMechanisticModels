def generate_pypesto_objective(ae: DeepMechanisticModel) -> JaxObjective:
    """
    Creates a pypesto objective function (this is the loss function) that
    needs to be minimized to train the respective autoencoder

    :param ae:
        Autoencoder that will be trained

    :returns:
        Objective function that needs to be minimized for training.
    """

    return JaxObjective(
        ae.pypesto_subproblem.objective, ae.embedding, x_names=ae.x_names
    )


def create_pypesto_problem(
    ae: DeepMechanisticModel, problem: Problem
) -> pypesto.Problem:
    """
    Creates a pypesto pypesto_probme that defines the optimization pypesto_probme that
    needs to be solved for the training of the provided autoencoder

    :param ae:
        Autoencoder that will be trained

    :returns:
        Optimization pypesto_probme that needs to be solved for training.
    """
    return pypesto.Problem(
        objective=generate_pypesto_objective(ae),
        x_names=ae.x_names,
        lb=[-np.inf for _ in ae.x_names],
        ub=[np.inf for _ in ae.x_names],
    )


OIREG = "oreg_inflate"
OEREG = "oreg_encode"
L1IREG = "l1reg_inflate"
L1EREG = "l1reg_encode"


def train(
    model: DeepMechanisticModel,
    problem_train: pypesto.Problem,
    problem_test: pypesto.Problem,
    rfile: Path,
    conf: Dict,
    schedule_config: Dict,
    n_epoch,
    x0,
    use_early_stopping,
    patience,
    min_improvement,
) -> pypesto.Result:
    """
    Trains the provided autoencoder by solving the optimization problem
    generated by :py:func:`create_pypesto_problem`
    """

    repo = git.Repo(search_parent_directories=True)

    wandb.init(
        project=f"DeepMechanisticModels.{conf['data']}.{conf['model']}",
        group=f"{conf['context']}_{conf['features']}",
        config={
            **conf,
            "patience": patience,  # logging patience hyperparam
            "schedule_config": schedule_config,
            "optimizer": "adam",
            "scheduler": "linear",
        },
        name="__".join(
            str(x)
            for x in (
                conf["job"],
                conf["samples"],
                conf["n_hidden"],
                conf["orth_reg_strategy"],
                conf["l1reg_inflate"],
                conf["oreg_inflate"],
                conf["l1reg_encode"],
                conf["oreg_encode"],
            )
        ),
        settings=wandb.Settings(
            start_method="fork",
            git_commit=repo.head.object.hexsha,
            git_remote_url=repo.remotes.origin.url,
        ),
    )

    wandb.define_metric("rmse_train", summary="min")
    wandb.define_metric("rmse_val", summary="min")
    wandb.define_metric("patience_counter")
    wandb.define_metric("fval", summary="min")
    # wandb.define_metric(L1IREG, summary="min")
    # wandb.define_metric(OIREG, summary="min")
    # wandb.define_metric(OEREG, summary="min")
    # wandb.define_metric(L1EREG, summary="min")

    par_labels = ("encode", "inflate", "kinetic")
    par_dims = (
        model.n_encode_weights,
        model.n_encoder_pars,
        model.n_kin_params,
    )
    for val_type, xname in itt.product(("x", "g"), par_labels):
        wandb.define_metric(f"{val_type}_{xname}")

    x = x0.copy()

    # Optimiser and related schedule defined here
    # TODO @GiacomoFabrini: change optimiser to optax.adamw (weight decay) and change schedule (later?!)
    schedule = linear_schedule(**schedule_config)
    opt = adam(schedule)
    opt_state = opt.init(x)

    opt_x = x.copy()
    opt_fval = np.inf
    opt_grads = np.NaN * np.ones_like(x)
    rmse_test_min = np.inf

    # Check Early-stopping parameters have been set correctly and instantiate early stopper
    if use_early_stopping:
        if patience is None:
            raise ValueError("Patience value for early stopping is undefined.")
        elif min_improvement is None:
            raise ValueError("Minimum absolute improvement for early stopping is undefined.")
        else:
            early_stop = EarlyStopping(
                min_delta=min_improvement,
                patience=patience
            )

    # Training loop
    for epoch in range(n_epoch + 1):
        # TODO @GiacomoFabrini ask Fabian: how can we reconcile this with the equinox gradient PyTree?
            # do I need to convert the PyTree to the same massive array in order to combine them?
        fval, grads = problem_train.objective(x, sensi_orders=(0, 1))

        # TODO @GiacomoFabrini replace with single loss function (and log that!!!)
            # for now, I have simply removed the W&B logging of the individual loss components
        for reg_fun, label in zip(
            (
                model.l1_inflate_reg,
                model.l1_encode_reg,
                model.orth_inflate_reg,
                model.orth_encode_reg,
            ),
            (L1IREG, L1EREG, OIREG, OEREG),
        ):
            # this is where the scale parameter of the various regularisation
            # methods get changed via the hyperparameters in training_configuration.py
            if conf[label] > 0:
                v_reg, g_reg = value_and_grad(reg_fun, argnums=0)(
                    x,
                    scale=conf[label]
                )
                # wandb.log({label: v_reg}, step=epoch)
                grads += g_reg

        wandb.log({"fval": fval}, step=epoch)
        if epoch % 5 == 0:
            rmses = dict()
            # evaluate rmse on train and test dataset only after a certain number (5) of epochs
            for dataset, pp in zip(
                ("train", "test"), (problem_train, problem_test)
            ):
                rmses[dataset] = rmse(pp, x)

            if rmses["test"] < rmse_test_min:
                rmse_test_min = rmses["test"]
                opt_x = x.copy()
                opt_fval = fval
                opt_grads = grads.copy()

            wandb.log(
                {
                    "rmse_train": rmses["train"],
                    "rmse_val": rmses["test"],
                    **{
                        f"{val_type}_{xname}": None
                        if not np.all(np.isfinite(value))
                        else wandb.Histogram(value)
                        if val_type == "x"
                        else wandb.Histogram(
                            np.log10(np.abs(value[value != 0]))
                        )
                        for val_type, values in (
                            ("x", x),
                            ("g", grads),
                        )
                        for xname, value in zip(
                            par_labels,
                            np.split(values, par_dims[:-1]),
                        )
                    },
                },
                step=epoch,
            )

            if use_early_stopping:
                # Update early stopper
                early_stop = early_stop.update(rmses["test"])
                # Debugging statements
                print(
                    f"epoch {epoch} | "
                    f"loss {rmses['test']} | "
                    f"has improved? {early_stop.has_improved} | "
                    f"patience count {early_stop.patience_count}"
                )
                # Log current patience count
                wandb.log(
                    {
                        "patience_counter": early_stop.patience_count,
                    },
                    step=epoch,
                )
                # Stop training if we have run out of patience
                if early_stop.should_stop:
                    print(f'Met early stopping criteria, breaking at epoch {epoch}')
                    break

        updates, opt_state = opt.update(grads, opt_state)
        x = apply_updates(x, updates)

        if np.any(np.isnan(x)):
            break

    wandb.finish()

    # Saving epoch number inside n_fval (number of function evaluations)
    OResult = OptimizeResult()
    OResult.append(
        OptimizerResult(
            fval=opt_fval,
            n_fval=epoch,  # save epoch number to diagnose early stopping
            x=opt_x,
            grad=opt_grads,
            x0=x0,
            id=str(conf["job"]),
        )
    )
    result = Result(
        problem=problem_train,
        optimize_result=OResult,
    )

    rfile.parent.mkdir(exist_ok=True, parents=True)
    writer = OptimizationResultHDF5Writer(str(rfile))
    writer.write(result, overwrite=True)

    return result


def rmse(pp, xx):
    try:
        x = pp.objective.jax_fun(xx)
        obj = pp.objective.base_objective
        amici_model = obj.amici_model
        petab_problem = obj.amici_object_builder.petab_problem
        res = obj(x, mode=MODE_RES, return_dict=True)
        simulation_df = rdatas_to_simulation_df(
            res[RDATAS],
            model=amici_model,
            measurement_df=petab_problem.measurement_df,
        )
        return np.sqrt(
            np.mean(
                np.square(
                    simulation_df[petab.SIMULATION]
                    - petab_problem.measurement_df[petab.MEASUREMENT]
                )
            )
        )
    except Exception as e:
        print(e)
        return np.NaN
